const DICTS = { vi, en };
export const LANGS = [['vi', 'Tiếng Việt'], ['en', 'English']];

function detect() {
  try {
    const saved = localStorage.getItem('drive.lang');
    if (saved && DICTS[saved]) return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

let lang = detect();

export function getLang() { return lang; }
export function locale() { return lang === 'vi' ? 'vi-VN' : 'en-GB'; }

export function setLang(code) {
  if (!DICTS[code]) return;
  lang = code;
  try { localStorage.setItem('drive.lang', code); } catch { /* storage blocked */ }
}

function fill(s, params) {
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}

export function t(key, params) {
  const s = DICTS[lang][key] ?? en[key];
  return s === undefined ? key : fill(s, params);
}

// Count-aware: uses "<key>.one" when n is 1 and that key exists.
export function tn(key, n, params) {
  const p = { ...params, n: new Intl.NumberFormat(locale()).format(n) };
  if (n === 1 && (DICTS[lang][key + '.one'] ?? en[key + '.one']) !== undefined) return t(key + '.one', p);
  return t(key, p);
}

// Fills static markup: data-i18n (text), data-i18n-label (aria-label), data-i18n-placeholder.
export function applyI18n(root) {
  document.documentElement.lang = lang;
  for (const n of root.querySelectorAll('[data-i18n]')) n.textContent = t(n.dataset.i18n);
  for (const n of root.querySelectorAll('[data-i18n-label]')) n.setAttribute('aria-label', t(n.dataset.i18nLabel));
  for (const n of root.querySelectorAll('[data-i18n-placeholder]')) n.setAttribute('placeholder', t(n.dataset.i18nPlaceholder));
}

export const _dicts = DICTS; // for the key-coverage check
